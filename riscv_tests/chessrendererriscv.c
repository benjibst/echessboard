#define COLOR_BITS 2
#define PX_PER_INT 16
#define IMG_WIDTH_PX 640
#define IMG_WIDTH_INT 40
#define IMG_HEIGHT_PX 480
#define CB_SIDE_PX 384
#define CB_SIDE_INT 24
#define SQUARE_SIDE_PX 48
#define SQUARE_SIDE_INT 3
#define TOP_BORDER_PX 48
#define BOTTOM_BORDER_PX 48
#define LEFT_BORDER_INT 8
#define RIGHT_BORDER_INT 8

#define PIECE_COLOR_BIT (1 << 7) // 0 for white, 1 for black
#include <stdio.h>
int main(void)
{
    int background = 0xFFFFFFFF; // 0b11 for every pixel -> same color as black pieces
    // draw top portion of background
    int curr_pixel = 0;
    int piece_data = 0; // piece data is for 4 pieces of a column, each piece is 1 byte
    int chess_pos_idx = 0;
    int piece_shift = 24;
    int piece = 0;
    int piece_row_offset = 0;
    int curr_16px_data = 0;
    int square_color = 0;
    int piece_color = 0;

    for (int z=0;z<1;z++)
    {
        // TOP BORDER 48 PX
        for (int i = 0; i < IMG_WIDTH_INT * TOP_BORDER_PX; i++)
        {
            framebuffer[curr_pixel++] = background;
        }

        // FOR EVERY ROW OF THE CHESS BOARD
        for (int curr_row = 0; curr_row < 8; curr_row++)
        {
            // FOR EVERY PIXEL ROW OF THE CURRENT CHESS BOARD ROW
            for (int y_in_row = 0; y_in_row < SQUARE_SIDE_PX; y_in_row++)
            {
                //LEFT BORDER
                for (unsigned int j = 0; j < LEFT_BORDER_INT; j++)
                {
                    framebuffer[curr_pixel++] = background;
                }


                // FOR EVERY COLUMN OF THE CURRENT ROW
                piece_shift = 24;
                for (int r = 0; r < 8; r++)
                {
                    chess_pos_idx = curr_row << 1;
                    if(r>=4) chess_pos_idx++;
                    if(r==4) piece_shift = 24;

                    piece_data = chess_pos[chess_pos_idx];
                    piece = (piece_data >> piece_shift) & 0xFF; // get the piece for the current column
                    piece_shift-=8;
                    piece_color = (piece & PIECE_COLOR_BIT) ? 0xFFFFFFFF : 0xAAAAAAAA; // determine piece color

                    for(int intincol = 0; intincol < SQUARE_SIDE_INT; intincol++)
                    {
                        curr_16px_data = pieces_img[piece&7][piece_row_offset + intincol];
                        framebuffer[curr_pixel++] = (curr_16px_data & piece_color) | (~curr_16px_data & square_color); // draw the piece with its color
                    }
                    square_color ^= 0x55555555; // toggle square color every 48 pixels 0x555 is 0b010101010101
                }

                
                //RIGHT BORDER
                for (unsigned int j = 0; j < RIGHT_BORDER_INT; j++)
                {
                    framebuffer[curr_pixel++] = background;
                }
                piece_row_offset += SQUARE_SIDE_INT;
            }
            piece_row_offset = 0; // reset the piece row offset for the next row
            square_color ^= 0x55555555; // toggle square color every 48 pixels 0x555 is 0b010101010101
        }
        chess_pos_idx = 0;
        for (int i = 0; i < IMG_WIDTH_INT * BOTTOM_BORDER_PX; i++)
        {
            framebuffer[curr_pixel++] = background;
        }
        curr_pixel = 0;
    }
    for (unsigned int i = 0; i < IMG_WIDTH_INT*IMG_HEIGHT_PX; i++)
    {
        if(!(i%IMG_WIDTH_INT)) printf("\n");
        printf("%08x ", framebuffer[i]);
    }
}